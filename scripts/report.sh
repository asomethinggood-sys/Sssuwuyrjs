#!/usr/bin/env bash
# report.sh - turn the NDJSON check log into machine- and human-readable reports.
#
# The report states only what was observed. Checks that were never executed are
# reported as UNTESTED, never omitted and never counted as passes.
set -o errexit
set -o nounset
set -o pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT_JSON="${WG_REPORT_FILE}"
OUT_MD="${WG_MARKDOWN_FILE}"

main() {
  wg_init_artifacts

  local checks_file="${WG_ARTIFACT_DIR}/checks.ndjson"
  [[ -f "$checks_file" ]] || : >"$checks_file"

  local preflight="{}"
  [[ -f "${WG_ARTIFACT_DIR}/preflight.json" ]] && preflight="$(cat "${WG_ARTIFACT_DIR}/preflight.json")"

  local git_sha="unknown" git_ref="unknown"
  git_sha="$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || echo unknown)"
  git_ref="$(git -C "$REPO_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)"

  jq -s \
    --argjson preflight "$preflight" \
    --arg generated "$(_wg_ts)" \
    --arg run_id "${WG_RUN_ID}" \
    --arg git_sha "$git_sha" \
    --arg git_ref "$git_ref" \
    --arg workflow "${GITHUB_WORKFLOW:-local}" \
    --arg run_url "${GITHUB_SERVER_URL:-https://github.com}/${GITHUB_REPOSITORY:-local}/actions/runs/${GITHUB_RUN_ID:-0}" \
    --arg runner "${RUNNER_NAME:-local}" \
    --arg image "${ImageOS:-unknown}${ImageVersion:-}" \
    '{
       schema: "wireguard-harness/test-report/v1",
       generated_at: $generated,
       run: { id: $run_id, workflow: $workflow, url: $run_url, runner: $runner,
              runner_image: $image, git_sha: $git_sha, git_ref: $git_ref },
       environment: $preflight,
       summary: {
         total:  (map(select(.id != "RUN-00")) | length),
         passed: (map(select(.status == "PASS")) | length),
         failed: (map(select(.status == "FAIL")) | length),
         skipped: (map(select(.status == "SKIP")) | length),
         untested: (map(select(.status == "UNTESTED")) | length),
         warned: (map(select(.status == "WARN")) | length)
       },
       checks: .
     }' "$checks_file" >"$OUT_JSON"

  local total passed failed skipped untested warned
  total="$(jq -r '.summary.total' "$OUT_JSON")"
  passed="$(jq -r '.summary.passed' "$OUT_JSON")"
  failed="$(jq -r '.summary.failed' "$OUT_JSON")"
  skipped="$(jq -r '.summary.skipped' "$OUT_JSON")"
  untested="$(jq -r '.summary.untested' "$OUT_JSON")"
  warned="$(jq -r '.summary.warned' "$OUT_JSON")"

  {
    printf '# WireGuard harness - test report\n\n'
    printf '| field | value |\n|---|---|\n'
    printf '| generated (UTC) | %s |\n' "$(_wg_ts)"
    printf '| harness run id | `%s` |\n' "$WG_RUN_ID"
    printf '| commit | `%s` (%s) |\n' "$git_sha" "$git_ref"
    printf '| runner | %s / %s |\n' "${RUNNER_NAME:-local}" "$(jq -r '.environment.kernel.release // "n/a"' "$OUT_JSON")"
    printf '| runner image | %s |\n' "${ImageOS:-unknown} ${ImageVersion:-}"
    printf '\n## Summary\n\n'
    printf '| result | count |\n|---|---|\n'
    printf '| PASS | %s |\n' "$passed"
    printf '| FAIL | %s |\n' "$failed"
    printf '| SKIP | %s |\n' "$skipped"
    printf '| UNTESTED | %s |\n' "$untested"
    printf '| WARN | %s |\n' "$warned"
    printf '| **total** | **%s** |\n\n' "$total"
    printf '> A check is only marked PASS when the underlying observation was made.\n'
    printf '> UNTESTED and SKIP are not passes. In particular, no claim of a working\n'
    printf '> handshake is made unless HS-01 reports a non-zero `latest-handshakes`\n'
    printf '> value read back from the kernel.\n\n'
    printf '## Platform capability snapshot\n\n```json\n'
    jq '.' <<<"$preflight"
    printf '```\n\n'
    printf '## Checks\n\n'
    printf '| id | result | description | detail | observed at |\n|---|---|---|---|---|\n'
    jq -r '.checks[] | "| `\(.id)` | \(.status) | \(.description) | \(.detail // "") | \(.timestamp) |"' "$OUT_JSON"
    printf '\n_Generated by scripts/report.sh; machine-readable data in test-report.json._\n'
  } >"$OUT_MD"

  wg_log "reports written: $OUT_JSON, $OUT_MD"
  printf '%s\n' "$total/$passed/$failed" >/dev/null
  jq -r '"checks=\(.summary.total) pass=\(.summary.passed) fail=\(.summary.failed) skip=\(.summary.skipped) untested=\(.summary.untested)"' "$OUT_JSON" >&2

  if [[ -n "${GITHUB_STEP_SUMMARY:-}" ]]; then
    {
      printf '## WireGuard harness results\n\n'
      printf 'passed **%s** / %s — failed **%s**, skipped %s, untested %s\n\n' \
        "$passed" "$total" "$failed" "$skipped" "$untested"
      printf '| id | result | description |\n|---|---|---|\n'
      jq -r '.checks[] | "| `\(.id)` | \(.status) | \(.description) |"' "$OUT_JSON"
      printf '\nFull report: `test-report.md` artifact for run [%s](%s).\n' \
        "${GITHUB_RUN_ID:-local}" "$(jq -r '.run.url' "$OUT_JSON")"
    } >>"$GITHUB_STEP_SUMMARY"
  fi

  # Composing a report is successful even when the report contains failures;
  # the suite derives its own exit status from the recorded checks.
  return 0
}

main "$@"
